int1 = input("Enter the first integer: ")
int2 = input("Enter the second integer: ")
int3 = input("Enter the third integer: ")

print(f"The sum of the three integers is: {int(int1) + int(int2) + int(int3)}")
print(f"First number - Second number = {int(int1) - int(int2)}")
print(f"Third number * First number = {int(int3) * int(int1)}")
print(f"The sum of all three numbers divided by the third number is: {(int(int1) + int(int2) + int(int3)) / int(int3)}")